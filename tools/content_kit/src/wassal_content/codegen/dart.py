"""Writes the app models: one freezed + json_serializable library per schema file (research R1).

`build_runner` then writes each library's `.freezed.dart` and `.g.dart` parts. Every class turns
off `copyWith`, `toString` and the `map`/`when` pattern helpers: content is read, never changed or
matched on, so they would only be dead code. `roots.dart` maps each part name to its root class's
`fromJson`, and `models.dart` exports everything.
"""

from __future__ import annotations

import textwrap

from wassal_content.codegen.ir import EnumDef, FieldDef, Model, ObjectDef, TypeRef, dart_member

__all__ = ["HEADER", "emit_dart"]

HEADER = (
    "// Generated by wassal-content codegen from content/schemas. Do not edit.\n"
    "// dart format off\n"
)

_PRIMITIVES = {"str": "String", "int": "int", "bool": "bool"}


_DART_ESCAPES = {
    **{code: f"\\u{{{code:x}}}" for code in [*range(0x20), 0x7F]},
    ord("\n"): "\\n",
    ord("\r"): "\\r",
    ord("\\"): "\\\\",
    ord("'"): "\\'",
    ord("$"): "\\$",
}


def _string(text: str) -> str:
    return f"'{text.translate(_DART_ESCAPES)}'"


def _type(type_: TypeRef) -> str:
    if type_.kind in _PRIMITIVES:
        return _PRIMITIVES[type_.kind]
    if type_.kind == "named":
        return type_.name
    if type_.item is None:
        raise ValueError(f"a {type_.kind} type needs an item type")
    if type_.kind == "list":
        return f"List<{_type(type_.item)}>"
    return f"Map<String, {_type(type_.item)}>"


def _doc(text: str, indent: str = "") -> list[str]:
    if not text:
        return []
    return [f"{indent}/// {line}" for line in textwrap.wrap(text, 76 - len(indent))]


def _enum(enum: EnumDef) -> list[str]:
    lines = [*_doc(enum.description), f"enum {enum.name} {{"]
    for value in enum.values:
        literal = str(value) if enum.is_int else _string(str(value))
        lines.append(f"  @JsonValue({literal})")
        lines.append(f"  {dart_member(value)},")
    lines.append("}")
    return lines


def _field(field: FieldDef) -> str:
    key = f"@JsonKey(name: {_string(field.json_name)})"
    if field.required:
        return f"    {key} required {_type(field.type)} {field.dart_name},"
    return f"    {key} {_type(field.type)}? {field.dart_name},"


def _object(obj: ObjectDef) -> list[str]:
    return [
        *_doc(obj.description),
        "@Freezed(",
        "  copyWith: false,",
        "  toStringOverride: false,",
        "  map: FreezedMapOptions.none,",
        "  when: FreezedWhenOptions.none,",
        ")",
        f"abstract class {obj.name} with _${obj.name} {{",
        f"  const factory {obj.name}({{",
        *(_field(field) for field in obj.fields),
        f"  }}) = _{obj.name};",
        "",
        f"  factory {obj.name}.fromJson(Map<String, dynamic> json) =>",
        f"      _${obj.name}FromJson(json);",
        "}",
    ]


def _library(model: Model, part: str) -> bytes:
    types = model.part_types(part)
    used = set().union(*(t.dependencies() for t in types)) if types else set()
    imports = sorted({model.by_name[name].part for name in used} - {part})
    lines = [
        *HEADER.rstrip("\n").split("\n"),
        "// ignore_for_file: invalid_annotation_target",
        "",
        "import 'package:freezed_annotation/freezed_annotation.dart';",
        "",
    ]
    if imports:
        lines.extend(f"import '{other}.dart';" for other in imports)
        lines.append("")
    lines.extend([f"part '{part}.freezed.dart';", f"part '{part}.g.dart';"])
    for type_ in types:
        lines.append("")
        lines.extend(_enum(type_) if isinstance(type_, EnumDef) else _object(type_))
    return ("\n".join(lines) + "\n").encode()


def _roots(model: Model) -> bytes:
    lines = [*HEADER.rstrip("\n").split("\n"), ""]
    lines.extend(f"import '{part}.dart';" for part in sorted(model.roots))
    lines.extend(
        [
            "",
            "/// The schema set these models were generated from.",
            f"const String schemaSetVersion = {_string(model.schema_set_version)};",
            "",
            "/// Parses a document of one pack part, keyed by its schema file's name.",
            "final Map<String, Object Function(Map<String, dynamic>)> rootFromJson = {",
            *(f"  {_string(part)}: {name}.fromJson," for part, name in sorted(model.roots.items())),
            "};",
        ]
    )
    return ("\n".join(lines) + "\n").encode()


def _barrel(model: Model) -> bytes:
    lines = [*HEADER.rstrip("\n").split("\n"), ""]
    lines.extend(f"export '{name}.dart';" for name in sorted([*model.parts, "roots"]))
    return ("\n".join(lines) + "\n").encode()


def emit_dart(model: Model) -> dict[str, bytes]:
    """Every generated Dart file, by file name."""
    files = {f"{part}.dart": _library(model, part) for part in model.parts}
    files["roots.dart"] = _roots(model)
    files["models.dart"] = _barrel(model)
    return files
