"""Writes the server models: Pydantic v2 classes in one module (research R1).

Mapping: objects → frozen `ContentModel` subclasses that ignore unknown fields (FR-008); integers,
strings and booleans → their strict types; string and integer enums → `StrEnum` and `IntEnum`;
arrays → tuples; maps → dicts; optional fields → `T | None = None`, left out on output.
"""

from __future__ import annotations

import json

from wassal_content.codegen.ir import EnumDef, FieldDef, Model, ObjectDef, TypeRef, python_member

__all__ = ["HEADER", "emit_python"]

HEADER = "# Generated by wassal-content codegen from content/schemas. Do not edit.\n"

_PRIMITIVES = {"str": "StrictStr", "int": "StrictInt", "bool": "StrictBool"}


def _annotation(type_: TypeRef) -> str:
    if type_.kind in _PRIMITIVES:
        return _PRIMITIVES[type_.kind]
    if type_.kind == "named":
        return type_.name
    if type_.item is None:
        raise ValueError(f"a {type_.kind} type needs an item type")
    if type_.kind == "list":
        return f"tuple[{_annotation(type_.item)}, ...]"
    return f"dict[StrictStr, {_annotation(type_.item)}]"


# Control characters other than a newline are written as escapes, so the source keeps them.
_DOC_CONTROLS = {code: f"\\x{code:02x}" for code in [*range(0x20), 0x7F] if code != 0x0A}


def _docstring(text: str, indent: str) -> list[str]:
    if not text:
        return []
    escaped = text.replace("\\", "\\\\").translate(_DOC_CONTROLS).replace('"', '\\"')
    return [f'{indent}"""{escaped}"""', ""]


def _field(field: FieldDef) -> str:
    annotation = _annotation(field.type)
    alias = field.py_name != field.json_name
    if field.required:
        value = f" = Field(alias={json.dumps(field.json_name)})" if alias else ""
        return f"    {field.py_name}: {annotation}{value}"
    if alias:
        value = f"Field(default=None, alias={json.dumps(field.json_name)})"
        return f"    {field.py_name}: {annotation} | None = {value}"
    return f"    {field.py_name}: {annotation} | None = None"


def _enum(enum: EnumDef) -> list[str]:
    base = "IntEnum" if enum.is_int else "StrEnum"
    lines = [f"class {enum.name}({base}):", *_docstring(enum.description, "    ")]
    for value in enum.values:
        literal = str(value) if enum.is_int else json.dumps(value)
        lines.append(f"    {python_member(value)} = {literal}")
    return lines


def _object(obj: ObjectDef) -> list[str]:
    lines = [f"class {obj.name}(ContentModel):", *_docstring(obj.description, "    ")]
    lines.extend(_field(field) for field in obj.fields)
    return lines


def emit_python(model: Model) -> bytes:
    """The whole `_generated.py` module."""
    blocks: list[list[str]] = [
        [
            HEADER.rstrip("\n"),
            f'"""Server models for the content schemas (schema set {model.schema_set_version}).',
            "",
            "Each class is one schema type. Unknown fields are ignored (FR-008), and optional",
            "fields are left out on output, never written as null.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "from enum import IntEnum, StrEnum",
            "",
            "from pydantic import BaseModel, ConfigDict, Field, StrictBool, StrictInt, StrictStr",
            "",
            f"SCHEMA_SET_VERSION = {json.dumps(model.schema_set_version)}",
        ],
        [
            "class ContentModel(BaseModel):",
            '    """The base of every generated model: frozen, and blind to unknown fields."""',
            "",
            '    model_config = ConfigDict(extra="ignore", frozen=True, populate_by_name=True)',
        ],
    ]
    for type_ in model.types:
        blocks.append(_enum(type_) if isinstance(type_, EnumDef) else _object(type_))
    roots = ["ROOT_MODELS: dict[str, type[ContentModel]] = {"]
    roots.extend(f"    {json.dumps(part)}: {name}," for part, name in sorted(model.roots.items()))
    roots.append("}")
    blocks.append(roots)
    return ("\n\n\n".join("\n".join(block) for block in blocks) + "\n").encode()
